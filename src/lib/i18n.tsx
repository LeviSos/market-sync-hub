const DICTS: Record<Lang, Dict> = { en, ru, uk };
const STORAGE_KEY = "caseforge.lang";

type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (key: keyof typeof en) => string };

const I18nContext = createContext<Ctx>({ lang: "en", setLang: () => {}, t: (k) => en[k] });

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");

  useEffect(() => {
    const stored = localStorage.getItem(STORAGE_KEY) as Lang | null;
    if (stored && stored in DICTS) setLangState(stored);
    else {
      const nav = navigator.language.slice(0, 2);
      if (nav === "ru" || nav === "uk") setLangState(nav);
    }
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    localStorage.setItem(STORAGE_KEY, l);
  }, []);

  const t = useCallback((key: keyof typeof en) => DICTS[lang][key] ?? en[key], [lang]);

  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}

export function useT() {
  return useContext(I18nContext).t;
}

const FLAGS: Record<Lang, string> = { en: "🇬🇧", ru: "🇷🇺", uk: "🇺🇦" };

export function LanguageSwitcher({ className = "" }: { className?: string }) {
  const { lang, setLang } = useI18n();
  const [open, setOpen] = useState(false);
  const current = LANGS.find((l) => l.code === lang) ?? LANGS[0];

  return (
    <div className={`relative ${className}`}>
      <button
        type="button"
        onClick={() => setOpen((v) => !v)}
        onBlur={() => setTimeout(() => setOpen(false), 120)}
        aria-expanded={open}
        className="flex items-center gap-1.5 rounded-md border border-border bg-surface px-2 py-1.5 font-display text-[11px] font-bold uppercase tracking-wide text-foreground transition-colors hover:bg-surface-2"
      >
        <span className="text-sm leading-none">{FLAGS[current.code]}</span>
        <span>{current.label}</span>
        <span className="text-[9px] leading-none text-muted-foreground">▾</span>
      </button>
      {open && (
        <div className="absolute right-0 z-50 mt-1 w-32 overflow-hidden rounded-md border border-border bg-background shadow-lg">
          {LANGS.map((l) => (
            <button
              key={l.code}
              type="button"
              onMouseDown={() => {
                setLang(l.code);
                setOpen(false);
              }}
              className={`flex w-full items-center gap-2 px-3 py-2 text-left font-display text-[11px] font-bold uppercase tracking-wide transition-colors hover:bg-surface ${
                lang === l.code ? "text-primary" : "text-muted-foreground"
              }`}
            >
              <span className="text-sm leading-none">{FLAGS[l.code]}</span>
              {l.label}
            </button>
          ))}
        </div>
      )}
    </div>
  );
}
